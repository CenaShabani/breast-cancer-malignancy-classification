"""Figure generation.

Kept out of the notebooks so the README's images and the notebooks' images are
the same objects, regenerated by one command. Each function returns the path it
wrote.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.calibration import calibration_curve
from sklearn.decomposition import PCA
from sklearn.metrics import auc as auc_score
from sklearn.metrics import precision_recall_curve, roc_curve
from sklearn.preprocessing import StandardScaler

from .data import feature_columns

FIGURE_DIR = Path(__file__).resolve().parents[1] / "outputs" / "figures"

MALIGNANT = "#c0392b"
BENIGN = "#2980b9"
ACCENT = "#8e44ad"
PALETTE = {1: MALIGNANT, 0: BENIGN, "M": MALIGNANT, "B": BENIGN}


def _setup() -> None:
    sns.set_theme(style="whitegrid", context="notebook")
    plt.rcParams.update(
        {
            "figure.dpi": 110,
            "savefig.dpi": 140,
            "savefig.bbox": "tight",
            "axes.titleweight": "bold",
            "axes.titlesize": 12,
            "font.size": 10,
        }
    )


def _save(fig, name: str) -> Path:
    FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    path = FIGURE_DIR / name
    fig.savefig(path)
    plt.close(fig)
    return path


def class_balance_and_scale(frame: pd.DataFrame) -> Path:
    """Why stratification and standardisation are both mandatory here."""
    _setup()
    fig, axes = plt.subplots(1, 2, figsize=(11, 4))

    counts = frame["diagnosis"].value_counts()
    axes[0].bar(
        ["Benign", "Malignant"],
        [counts["B"], counts["M"]],
        color=[BENIGN, MALIGNANT],
    )
    for i, v in enumerate([counts["B"], counts["M"]]):
        axes[0].text(i, v + 6, f"{v}\n({v/len(frame):.1%})", ha="center", fontsize=9)
    axes[0].set_ylim(0, 400)
    axes[0].set_ylabel("patients")
    axes[0].set_title("Class balance — 37% malignant")

    stds = frame[feature_columns(frame)].std().sort_values()
    axes[1].barh(range(len(stds)), stds.values, color=ACCENT, height=0.7)
    axes[1].set_xscale("log")
    axes[1].set_yticks([0, len(stds) - 1])
    axes[1].set_yticklabels([stds.index[0], stds.index[-1]], fontsize=8)
    axes[1].set_xlabel("standard deviation (log scale)")
    axes[1].set_title(
        f"Feature scales span {stds.max()/stds.min():,.0f}x — standardise or "
        "area dominates"
    )
    fig.tight_layout()
    return _save(fig, "01_class_balance_and_scale.png")


def correlation_structure(frame: pd.DataFrame) -> Path:
    """The block structure: 30 columns, far fewer independent measurements."""
    _setup()
    features = feature_columns(frame)
    corr = frame[features].corr()

    fig, ax = plt.subplots(figsize=(11, 9))
    sns.heatmap(
        corr,
        cmap="RdBu_r",
        center=0,
        vmin=-1,
        vmax=1,
        square=True,
        linewidths=0.3,
        cbar_kws={"shrink": 0.6, "label": "Pearson r"},
        xticklabels=True,
        yticklabels=True,
        ax=ax,
    )
    ax.tick_params(labelsize=7)
    # The mean / se / worst blocks are 10 columns each, in file order.
    for boundary in (10, 20):
        ax.axhline(boundary, color="black", lw=1.6)
        ax.axvline(boundary, color="black", lw=1.6)
    ax.set_title(
        "Feature correlation — mean / SE / worst blocks\n"
        "radius, perimeter and area are one measurement written three ways (r > 0.98)"
    )
    return _save(fig, "02_correlation_structure.png")


def univariate_separation(separation: pd.DataFrame) -> Path:
    """Which single measurements carry the signal, and which carry none."""
    _setup()
    ordered = separation.sort_values("auc")
    colours = [
        MALIGNANT if a >= 0.9 else (ACCENT if a >= 0.7 else "#95a5a6")
        for a in ordered["auc"]
    ]

    # Lollipops, not bars. The informative range is 0.44-0.98, so the x-axis has
    # to be truncated to show anything — and a truncated bar chart lies about
    # ratios by construction. A point sitting on a stem to the 0.5 null line
    # encodes the same values without implying the bar lengths are comparable.
    fig, ax = plt.subplots(figsize=(9, 8))
    ax.hlines(ordered["feature"], 0.5, ordered["auc"], color=colours, lw=2.2, alpha=0.55)
    ax.scatter(ordered["auc"], ordered["feature"], color=colours, s=42, zorder=3)
    ax.axvline(0.5, color="black", ls="--", lw=1.2)
    ax.text(0.503, 0.4, "no separation", fontsize=8, rotation=90, va="bottom")
    ax.set_xlim(0.42, 1.0)
    ax.set_xlabel("univariate AUC (malignant vs benign)")
    ax.tick_params(labelsize=8)
    ax.set_title(
        "Single-feature class separation\n"
        "the 'worst' measurements dominate; four SE features are indistinguishable "
        "from noise"
    )
    fig.tight_layout()
    return _save(fig, "03_univariate_separation.png")


def feature_distributions(frame: pd.DataFrame, features: list[str]) -> Path:
    """Distribution overlap for the strongest separators — and the zero spike."""
    _setup()
    fig, axes = plt.subplots(2, 3, figsize=(13, 7))
    for ax, column in zip(axes.ravel(), features):
        for label, colour, name in ((1, MALIGNANT, "Malignant"), (0, BENIGN, "Benign")):
            subset = frame.loc[frame["diagnosis"].eq("M").astype(int) == label, column]
            sns.kdeplot(subset, ax=ax, fill=True, alpha=0.45, color=colour, label=name, lw=1.5)
        ax.set_title(column, fontsize=10)
        ax.set_ylabel("")
        ax.legend(fontsize=8)
    fig.suptitle(
        "Class-conditional distributions — separation is strong but never complete",
        fontweight="bold",
    )
    fig.tight_layout()
    return _save(fig, "04_feature_distributions.png")


def pca_projection(X: pd.DataFrame, y: pd.Series) -> Path:
    """Two components, 63% of variance — the shape of the problem."""
    _setup()
    scaled = StandardScaler().fit_transform(X)
    pca = PCA(n_components=10, random_state=42).fit(scaled)
    coords = pca.transform(scaled)
    ratio = pca.explained_variance_ratio_

    fig, axes = plt.subplots(1, 2, figsize=(12, 4.8))
    for label, colour, name in ((0, BENIGN, "Benign"), (1, MALIGNANT, "Malignant")):
        mask = y.to_numpy() == label
        axes[0].scatter(
            coords[mask, 0], coords[mask, 1], s=16, alpha=0.65, c=colour, label=name,
            edgecolors="none",
        )
    axes[0].set_xlabel(f"PC1 ({ratio[0]:.1%} variance)")
    axes[0].set_ylabel(f"PC2 ({ratio[1]:.1%} variance)")
    axes[0].legend()
    axes[0].set_title("PCA — classes separate along PC1, with an overlap band")

    axes[1].bar(range(1, 11), ratio, color=ACCENT, alpha=0.8)
    axes[1].plot(range(1, 11), np.cumsum(ratio), "o-", color="black", lw=1.5, ms=4)
    axes[1].axhline(0.95, ls="--", color=MALIGNANT, lw=1.2)
    axes[1].text(1.2, 0.96, "95% variance", fontsize=8, color=MALIGNANT)
    axes[1].set_xlabel("principal component")
    axes[1].set_ylabel("variance explained")
    axes[1].set_title("PC1 alone carries 44.6% — the columns are highly redundant")
    fig.tight_layout()
    return _save(fig, "05_pca_projection.png")


def model_comparison(results: pd.DataFrame) -> Path:
    """Every reasonable model lands in the same place."""
    _setup()
    frame = results[results["model"] != "baseline (majority class)"].copy()
    frame = frame.sort_values("roc_auc")

    fig, axes = plt.subplots(1, 2, figsize=(13, 5), sharey=True)
    for ax, (metric, sd_col, title) in zip(
        axes,
        [
            ("roc_auc", "roc_auc_sd", "ROC AUC"),
            ("recall", "recall_sd", "Recall at the default 0.5 threshold"),
        ],
    ):
        ax.errorbar(
            frame[metric], frame["model"], xerr=frame[sd_col], fmt="o",
            color=ACCENT, ecolor="#bdc3c7", capsize=3, ms=6,
        )
        ax.set_xlabel(metric)
        ax.set_title(title)
        ax.tick_params(labelsize=9)
    axes[0].set_xlim(0.97, 1.0)
    fig.suptitle(
        "Model comparison, 10x10 repeated stratified CV (error bars = 1 SD across folds)\n"
        "the top six overlap within one standard deviation — model choice is not the lever",
        fontweight="bold",
    )
    fig.tight_layout()
    return _save(fig, "06_model_comparison.png")


def roc_and_pr(y_true, y_prob) -> Path:
    """Threshold-free performance on the held-out set."""
    _setup()
    fpr, tpr, _ = roc_curve(y_true, y_prob)
    precision, recall, _ = precision_recall_curve(y_true, y_prob)

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.8))
    axes[0].plot(fpr, tpr, color=MALIGNANT, lw=2, label=f"AUC = {auc_score(fpr, tpr):.4f}")
    axes[0].plot([0, 1], [0, 1], "--", color="grey", lw=1)
    axes[0].set_xlabel("false positive rate")
    axes[0].set_ylabel("true positive rate (sensitivity)")
    axes[0].set_title("ROC — held-out test set")
    axes[0].legend(loc="lower right")

    axes[1].plot(recall, precision, color=ACCENT, lw=2,
                 label=f"AP = {auc_score(recall, precision):.4f}")
    axes[1].axhline(np.mean(y_true), ls="--", color="grey", lw=1,
                    label=f"prevalence = {np.mean(y_true):.3f}")
    axes[1].set_xlabel("recall")
    axes[1].set_ylabel("precision")
    axes[1].set_title("Precision-recall — held-out test set")
    axes[1].legend(loc="lower left")
    fig.tight_layout()
    return _save(fig, "07_roc_and_pr.png")


def calibration(curves: dict[str, tuple]) -> Path:
    """Do the predicted probabilities mean what they say?"""
    _setup()
    fig, ax = plt.subplots(figsize=(6.5, 5.5))
    ax.plot([0, 1], [0, 1], "--", color="black", lw=1.2, label="perfectly calibrated")
    colours = [MALIGNANT, ACCENT, BENIGN, "#e67e22"]
    for (name, (y_true, y_prob, brier)), colour in zip(curves.items(), colours):
        true_frac, pred_frac = calibration_curve(y_true, y_prob, n_bins=10, strategy="quantile")
        ax.plot(pred_frac, true_frac, "o-", color=colour, lw=1.6, ms=5,
                label=f"{name} (Brier {brier:.4f})")
    ax.set_xlabel("mean predicted probability")
    ax.set_ylabel("observed malignant fraction")
    ax.set_title(
        "Calibration, out-of-fold on training data\n"
        "the threshold argument only works if these probabilities are honest"
    )
    ax.legend(fontsize=8, loc="upper left")
    fig.tight_layout()
    return _save(fig, "08_calibration.png")


def sensitivity_tradeoff(sweep: pd.DataFrame, targets: pd.DataFrame) -> Path:
    """The centrepiece: what each extra point of sensitivity costs."""
    _setup()
    fig, axes = plt.subplots(1, 2, figsize=(13, 5))

    ax = axes[0]
    ax.plot(sweep["threshold"], sweep["recall"], lw=2, color=MALIGNANT,
            label="sensitivity (recall)")
    ax.fill_between(sweep["threshold"], sweep["recall"] - sweep["recall_sd"],
                    sweep["recall"] + sweep["recall_sd"], color=MALIGNANT, alpha=0.15)
    ax.plot(sweep["threshold"], sweep["specificity"], lw=2, color=BENIGN,
            label="specificity")
    ax.fill_between(sweep["threshold"], sweep["specificity"] - sweep["specificity_sd"],
                    sweep["specificity"] + sweep["specificity_sd"], color=BENIGN, alpha=0.15)
    ax.axvline(0.5, ls="--", color="grey", lw=1.2)
    ax.text(0.515, 0.53, "default 0.5", fontsize=8, rotation=90, va="bottom")
    for _, row in targets[targets["reachable"]].iterrows():
        ax.axvline(row["threshold"], ls=":", color="black", lw=1, alpha=0.5)
    ax.set_xlabel("decision threshold")
    ax.set_ylabel("rate")
    ax.set_ylim(0.5, 1.005)
    ax.legend(loc="lower center")
    ax.set_title("Sensitivity and specificity across the threshold")

    ax = axes[1]
    reach = targets[targets["reachable"]]
    ax.plot(reach["recall"], reach["specificity"], "o-", color=ACCENT, lw=2, ms=8)
    # Labels alternate above/below the line so adjacent points do not collide.
    for i, (_, row) in enumerate(reach.iterrows()):
        above = i % 2 == 0
        ax.annotate(
            f"t={row['threshold']:.2f}\n{row['false_pos']:.0f} FP / {row['false_neg']:.1f} FN",
            (row["recall"], row["specificity"]),
            textcoords="offset points",
            xytext=(-14, 16 if above else -34),
            fontsize=8,
            ha="left",
        )
    ax.margins(x=0.16, y=0.22)
    ax.set_xlabel("sensitivity achieved")
    ax.set_ylabel("specificity retained")
    ax.set_title("The cost of not missing cancers\n(counts are per 455 training patients)")
    fig.suptitle(
        "Choosing the threshold is the actual modelling decision",
        fontweight="bold", y=1.02,
    )
    fig.tight_layout()
    return _save(fig, "09_sensitivity_tradeoff.png")


def coefficients(model, features: list[str], top: int = 15) -> Path:
    """What the final model actually learned, on standardised features."""
    _setup()
    coefs = pd.Series(model.named_steps["model"].coef_[0], index=features)
    ordered = coefs.reindex(coefs.abs().sort_values(ascending=False).index).head(top)[::-1]

    fig, ax = plt.subplots(figsize=(8, 6))
    ax.barh(ordered.index, ordered.values,
            color=[MALIGNANT if v > 0 else BENIGN for v in ordered.values], height=0.72)
    ax.axvline(0, color="black", lw=1)
    ax.set_xlabel("coefficient (standardised features; positive = pushes toward malignant)")
    ax.tick_params(labelsize=8)
    ax.set_title(
        f"Top {top} coefficients, L2 logistic regression\n"
        "read as association, not mechanism — the inputs are heavily collinear"
    )
    fig.tight_layout()
    return _save(fig, "10_coefficients.png")


def confusion_at_thresholds(y_true, y_prob, thresholds: dict[str, float]) -> Path:
    """The held-out confusion matrices side by side, default vs chosen."""
    _setup()
    from sklearn.metrics import confusion_matrix

    fig, axes = plt.subplots(1, len(thresholds), figsize=(5.2 * len(thresholds), 4.4))
    axes = np.atleast_1d(axes)
    for ax, (name, t) in zip(axes, thresholds.items()):
        cm = confusion_matrix(y_true, (np.asarray(y_prob) >= t).astype(int), labels=[0, 1])
        sns.heatmap(
            cm, annot=True, fmt="d", cmap="Purples", cbar=False, square=True,
            xticklabels=["pred benign", "pred malignant"],
            yticklabels=["benign", "malignant"], ax=ax, annot_kws={"size": 14},
        )
        tn, fp, fn, tp = cm.ravel()
        ax.set_title(
            f"{name} (t = {t:.2f})\n"
            f"sensitivity {tp/(tp+fn):.3f} | specificity {tn/(tn+fp):.3f} | "
            f"{fn} missed cancer{'s' if fn != 1 else ''}"
        )
    fig.suptitle("Held-out test set (114 patients), same model, two thresholds",
                 fontweight="bold")
    fig.tight_layout()
    return _save(fig, "11_confusion_matrices.png")
